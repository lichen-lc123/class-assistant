for f in FEATURES:
    for key,category in [('business','业务流程图'),('system','系统流程图')]:
        nodes,edges,w,h=renderer.layout(f[key])
        if key=='system':
            for i,(a,b,label) in enumerate(edges):
                pair=(int(a[1:]),int(b[1:])) if a.startswith('N') and b.startswith('N') else None
                if not label and pair in LABELS.get(f['name'],{}):
                    edges[i]=(a,b,LABELS[f['name']][pair])
        svg=renderer.draw_svg(f['name'],category,nodes,edges,w,h)
        svg=svg.replace('一期已实现功能。','课表导入待确认设计。').replace('V1.0','V0.5').replace('一期登录与账号管理','课表按学期管理 · 待确认后开发')
        renderer.write(ROOT/category/(f['name']+'.svg'),svg)
        mmd=renderer.mermaid(f['name'],category,nodes,edges).replace('V1.0','V0.5')
        renderer.write(ROOT/'Mermaid源文件'/category/(f['name']+'.mmd'),mmd)

