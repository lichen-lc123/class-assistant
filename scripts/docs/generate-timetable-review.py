for file in ROOT.rglob('*.svg'):
    ET.parse(file)
    assert '待确认' in file.read_text(encoding='utf-8')
    assert '已实现' not in file.read_text(encoding='utf-8')
for file in ROOT.rglob('*.md'):
    for href in re.findall(r'\]\(([^)]+)\)',file.read_text(encoding='utf-8')):
        assert (file.parent/href).exists(),href
