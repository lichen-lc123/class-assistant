def validate():
    checked = 0
    for feature in FEATURES:
        folder = ROOT / feature['module']
        for category in ['业务流程图', '系统流程图']:
            svg = folder / '流程图' / category / (feature['name'] + '.svg')
            tree = ET.parse(svg)
            assert tree.getroot().tag.endswith('svg')
            source = folder / '流程图源文件' / category / (feature['name'] + '.mmd')
            text = source.read_text(encoding='utf-8')
            assert 'flowchart TD' in text and DATE in text
            checked += 1
    paths = [ROOT/'功能表'/'MEM2602功能总表.md'] + [ROOT / m / '文档目录.md' for m in ['', '课表功能', '作业功能', '发布运维']]
    paths += [ROOT / f['module'] / '需求规格说明书' / (f['name'] + '.md') for f in FEATURES]
    for path in paths:
        for target in re.findall(r'\]\(([^)]+)\)', path.read_text(encoding='utf-8')):
            assert (path.parent / target).resolve().exists(), (path, target)
    for source in {s for feature in FEATURES for s in feature['sources']}:
        assert (ROOT.parent / source).exists(), source
    print(f'Validated {len(FEATURES)} current specifications, {checked} SVGs, {checked} Mermaid sources and function/index links.')

