def graph(steps):
    nodes, edges, width, height = r.layout(steps)
    y = 145
    for node in [n for n in nodes if n['id'].startswith('N')]:
        branch = next((n for n in nodes if n['id'] == 'B' + node['id'][1:]), None)
        if node['kind'] == 'database':
            node['h'] = max(node['h'], 100)
        node['y'] = y
        if branch:
            branch['y'] = y + max(0, (node['h'] - branch['h']) / 2)
        y = max(node['y'] + node['h'], branch['y'] + branch['h'] if branch else 0) + 74
    for index, step in enumerate(steps, 1):
        if isinstance(step, dict) and step.get('resume'):
            edges.append((f'B{index}', f'N{index+1}', ''))
    return nodes, edges, width, int(y + 30)

def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')

def generate_feature(feature):
    folder = ROOT / feature['module']
    name = feature['name']
    for key, category in [('business', '业务流程图'), ('system', '系统流程图')]:
        chart = graph(feature[key])
        nodes, edges, width, height = chart
        merges = [edge for edge in edges if edge[0].startswith('B')]
        svg = r.draw_svg(name, category, nodes, [edge for edge in edges if edge not in merges], width, height).replace('一期已实现功能。', '当前已实现功能。').replace('V1.0', '当前版').replace('一期登录与账号管理', 'MEM2602 当前业务规则')
        if merges:
            svg = svg.replace('异常分支在本次处理结束，修正后重新发起。', '带回线的分支继续后续步骤；其余结果可修正后重试。')
            lookup = {n['id']: n for n in nodes}
            paths = []
            for first, last, _ in merges:
                a, b = lookup[first], lookup[last]
                middle = b['y'] - 37
                x, y0 = a['x'] + a['w'], a['y'] + a['h']/2
                target = b['x'] + b['w']/2
                path = f'M{x} {y0} L1070 {y0} L1070 {middle} L{target} {middle} L{target} {b["y"]-4}'
                paths.append(f'<path d="{path}" stroke="#7E8C7A" stroke-width="1.7" fill="none" marker-end="url(#arrow)"/>')
            svg = svg.replace('</g></svg>', '\n'.join(paths) + '</g></svg>')
        write(folder / '流程图' / category / (name + '.svg'), svg)
        write(folder / '流程图源文件' / category / (name + '.mmd'), r.mermaid(name, category, chart[0], chart[1]).replace('V1.0', '当前版'))
